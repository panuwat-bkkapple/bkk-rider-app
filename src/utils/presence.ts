// สวิตช์ "รับงาน/ปิดรับ" ต้องมีผลจริงในฐานข้อมูล — ก่อนหน้านี้ไม่มี
//
// riders/{id}/status ถูกเขียนเป็น Online/Busy ก็ต่อเมื่อไรเดอร์กดรับงานแล้ว GPS
// ยิงพิกัดกลับมา (useRiderData) ส่วนการกด "ปิดรับ" แค่ setIsOnline(false) แล้วหยุด
// เขียน GPS — ค่าเดิมค้างอยู่ในฐานข้อมูลตลอดกาล **ไม่มีใครในทั้ง 3 รีโปเขียน
// Offline เลย** (grep แล้ว, รายงานสำรวจ push ข้อ C) ผลคือ:
//   · DispatcherPage ของแอดมินกรอง `status !== 'Offline'` มาตลอดแต่ไม่เคยกรองใครออก
//   · จุดสีเขียวใน RiderManagement ค้างแม้ไรเดอร์ปิดรับไปแล้ว
//   · broadcast (#152) ต้องเลิกดู presence เพราะมันไม่มีความหมาย
//
// เจ้าของงานเคาะ 4 ก.ย. 2569: ปิดรับ = หายจากรายชื่อจ่ายงาน + ไม่ได้ push broadcast
// ไฟล์นี้คือกติกาว่า "เมื่อไหร่ต้องเขียน Offline" แยกออกมาให้เทสได้ ส่วน writer จริง
// อยู่ใน useRiderData
//
// **ไม่ใช้ onDisconnect โดยตั้งใจ** — RTDB ตัดการเชื่อมต่อทุกครั้งที่ iOS พับ PWA
// หรือเน็ตสะดุด ถ้าผูก Offline ไว้กับมัน ไรเดอร์ที่กำลังขี่อยู่โดยล็อกหน้าจอจะ
// หายจากรายชื่อจ่ายงานทั้งที่เปิดรับอยู่ Offline จึงต้องมาจากการกดเท่านั้น

export const PRESENCE_OFFLINE = 'Offline';

/** ต้องเขียน Offline ลงฐานข้อมูลไหม — เฉพาะตอนสวิตช์ **เปลี่ยน** จากเปิดเป็นปิด
 *  ไม่ใช่ทุกครั้งที่ค่าเป็น false (ตอน mount ค่าเริ่มต้นคือ false อยู่แล้ว การเขียน
 *  ตรงนั้นจะทับสถานะของกะที่ยังไม่จบเมื่อไรเดอร์แค่เปิดแอปขึ้นมาใหม่) */
export function offlineWriteNeeded(prev: boolean | undefined, next: boolean): boolean {
  return prev === true && next === false;
}

/** ค่า status ในฐานข้อมูลบอกว่ากะยังเปิดอยู่ไหม — ใช้ตอนเปิดแอปเพื่อให้สวิตช์บนจอ
 *  ตรงกับสิ่งที่แอดมินเห็น (เดิมสวิตช์เริ่มที่ปิดเสมอขณะที่ฐานข้อมูลยังบอกว่าเปิด) */
export function presenceIsOn(status: unknown): boolean {
  return status === 'Online' || status === 'Busy';
}
