// กลอน PIN ตามเวลาจริง — ตรรกะล้วน ไม่มี React ไม่มี side effect
//
// แทนที่ `useAutoLogout` เดิมซึ่งเป็น `setTimeout` 30 นาทีล้วน และเพี้ยนได้
// **ทั้งสองทาง** บน iOS PWA (รายงานสำรวจ 3 ก.ย. 2569 ข้อ 2):
//
//   - หลุดเร็วเกิน: iOS แช่ timer ตอนแอปอยู่เบื้องหลัง พอกลับมา timer ที่เลย
//     กำหนดยิงทันที — สลับไปเปิดแผนที่ 31 นาทีแล้วกลับมา = โดนเตะออก
//   - ไม่หลุดเลย: ถ้า iOS **ฆ่าหน้าเว็บทิ้ง** timer หายไปพร้อมกัน เปิดใหม่แล้ว
//     localStorage ยังครบ = เข้าได้ทันทีไม่ว่าทิ้งไว้นานแค่ไหน
//
// ตัวนี้อ่าน**นาฬิกาจริง**จาก timestamp ที่ประทับตอนแอปถูกซ่อน จึงตอบถูกทั้ง
// สองเคส และที่สำคัญกว่า: มัน **ล็อก ไม่ใช่ signOut** — Firebase session
// อยู่ต่อ การลงทะเบียนเครื่องอยู่ต่อ ปลดกลอนด้วย PIN 4 หลักจบ (หลักการข้อ 3)

export const LOCK_AFTER_MS = 30 * 60 * 1000; // 30 นาที
export const LAST_HIDDEN_KEY = 'last_hidden_at';

/**
 * ถึงเวลาล็อกหรือยัง
 *
 * @param lastHiddenAt ค่าที่อ่านจาก localStorage (string | null)
 * @param now เวลาปัจจุบัน
 *
 * ไม่มี timestamp = ไม่ล็อก — แอปที่เพิ่งติดตั้งหรือยังไม่เคยถูกซ่อนเลย ไม่ควร
 * ขอ PIN ทันทีที่เปิด (ผู้ใช้เพิ่งใส่รหัสผ่านไปเมื่อกี้)
 *
 * ค่าเสีย (NaN / ไม่ใช่ตัวเลข) = ไม่ล็อก โดยตั้งใจ — ไม่ใช่ fail-open ที่
 * อันตราย เพราะกลอนนี้ป้องกัน "คนอื่นหยิบเครื่องที่ปลดล็อกไว้" ไม่ใช่การ
 * ยืนยันตัวตนกับ server (Firebase session ยังเป็นตัวคุมสิทธิ์จริงเสมอ)
 * ส่วนการล็อกผิดพลาดกลางกะทำให้ไรเดอร์เสียเวลาหน้างาน
 *
 * เวลาในอนาคต (นาฬิกาเครื่องถูกปรับถอยหลัง) = ไม่ล็อก — **ไม่ได้มี guard แยก
 * ให้เรื่องนี้ และไม่ควรมี**: elapsed ที่ติดลบเทียบกับ LOCK_AFTER_MS ที่เป็นบวก
 * ได้ false อยู่แล้วเสมอ เคยเขียน `if (elapsed < 0) return false;` ไว้ตรงนี้ แต่
 * injection พิสูจน์ว่าถอดออกแล้วเทสยังเขียวทุกตัว = ไม่มีอินพุตไหนไปถึงมันได้เลย
 * จึงลบทิ้งตามกฎ "ด่านที่ไปไม่ถึง ให้ลบ ไม่ใช่ ship" เทสของเคสนี้ยังอยู่เพราะมัน
 * ตรึง**พฤติกรรม** ที่ถูกต้อง ไม่ใช่ตรึงบรรทัดที่ถูกลบไป
 */
export function shouldLock(lastHiddenAt: string | null, now: number): boolean {
  if (!lastHiddenAt) return false;
  const t = Number(lastHiddenAt);
  if (!Number.isFinite(t) || t <= 0) return false;
  return now - t > LOCK_AFTER_MS;
}
