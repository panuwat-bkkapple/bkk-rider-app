// ที่มา (3 ก.ย. 2569): ระงับบัญชีเพื่อทดสอบ แล้วจอล็อกอินขึ้นว่า
// **"ข้อผิดพลาดระบบ: Firebase: Error (auth/user-disabled)."** — catch-all เดิม
// ดักไว้แค่ `auth/invalid-credential` กับ `auth/wrong-password` นอกนั้นเอา
// `err.message` ดิบมาโชว์ ไรเดอร์ตัวจริงที่ถูกระงับจึงเห็นภาษาอังกฤษของ SDK
// ซึ่งบอกไม่ได้ว่าต้องทำอะไรต่อ
//
// กติกาสองข้อของไฟล์นี้:
//   1. **ห้ามโชว์ข้อความดิบของ SDK ให้ไรเดอร์** — code ที่ไม่รู้จักได้ข้อความกลางๆ
//      ที่ยังบอกทางออกได้ (ติดต่อออฟฟิศ)
//   2. **แต่ห้ามทิ้ง code ดิบ** — call site ยัง `console.error` ตัวเต็มไว้เสมอ
//      เพราะเวลาไรเดอร์โทรมาแจ้ง "เข้าไม่ได้" สิ่งที่ต้องรู้คือ code อะไร

const LOGIN_MESSAGES: Record<string, string> = {
  // สามตัวนี้ยุบเป็นข้อความเดียวโดยตั้งใจ — การแยก "ไม่มีอีเมลนี้" ออกจาก
  // "รหัสผ่านผิด" คือการบอกคนนอกว่าอีเมลไหนมีอยู่ในระบบ (account enumeration)
  'auth/invalid-credential': 'อีเมลหรือรหัสผ่านไม่ถูกต้อง กรุณาตรวจสอบอีกครั้ง',
  'auth/wrong-password': 'อีเมลหรือรหัสผ่านไม่ถูกต้อง กรุณาตรวจสอบอีกครั้ง',
  'auth/user-not-found': 'อีเมลหรือรหัสผ่านไม่ถูกต้อง กรุณาตรวจสอบอีกครั้ง',

  'auth/user-disabled': 'บัญชีนี้ถูกระงับการใช้งาน กรุณาติดต่อออฟฟิศ',
  'auth/invalid-email': 'รูปแบบอีเมลไม่ถูกต้อง',
  'auth/too-many-requests': 'ลองเข้าสู่ระบบผิดหลายครั้งเกินไป กรุณารอสักครู่แล้วลองใหม่',

  // ไรเดอร์อยู่บนถนน สัญญาณหลุดเป็นเรื่องปกติที่สุดที่จะเจอ — ต้องแยกออกจาก
  // "รหัสผ่านผิด" ให้ชัด ไม่งั้นเขาจะนั่งพิมพ์รหัสซ้ำอยู่ตรงนั้นทั้งที่ปัญหาคือเน็ต
  'auth/network-request-failed': 'เชื่อมต่อไม่สำเร็จ กรุณาตรวจสอบสัญญาณอินเทอร์เน็ตแล้วลองใหม่',
};

const LOGIN_FALLBACK = 'เข้าสู่ระบบไม่สำเร็จ กรุณาลองใหม่อีกครั้ง หากยังไม่ได้กรุณาติดต่อออฟฟิศ';

export function loginErrorMessage(code: unknown): string {
  return LOGIN_MESSAGES[String(code ?? '')] || LOGIN_FALLBACK;
}

const RESET_MESSAGES: Record<string, string> = {
  'auth/invalid-email': 'รูปแบบอีเมลไม่ถูกต้อง',
  'auth/too-many-requests': 'ขอลิงก์บ่อยเกินไป กรุณารอสักครู่แล้วลองใหม่',
  'auth/network-request-failed': 'เชื่อมต่อไม่สำเร็จ กรุณาตรวจสอบสัญญาณอินเทอร์เน็ตแล้วลองใหม่',
};

// เดิมทุก error ที่ไม่ใช่ `invalid-email` ตกมาที่ "ไม่พบอีเมลนี้ในระบบ หรือเกิด
// ข้อผิดพลาด" ซึ่ง **บอกข้อมูลผิด**: ไรเดอร์ที่เน็ตหลุดจะอ่านว่าอีเมลตัวเองไม่มี
// ในระบบ. ข้อความกลางไม่ยืนยันว่ามีหรือไม่มีอีเมลนั้น (กันการเดาบัญชีด้วย)
const RESET_FALLBACK = 'ส่งลิงก์ไม่สำเร็จ กรุณาลองใหม่อีกครั้ง หากยังไม่ได้กรุณาติดต่อออฟฟิศ';

export function resetPasswordErrorMessage(code: unknown): string {
  return RESET_MESSAGES[String(code ?? '')] || RESET_FALLBACK;
}
